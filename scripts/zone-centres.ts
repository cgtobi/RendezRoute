// Rebuilds src/client/zone-centres.ts (decision D63): the main place of every IANA time zone, from
// the tz database's zone.tab (public domain), so the form map can open on the visitor's zone.
//
//   npm run zones [-- <path of zone.tab> [<path of tzdata.zi>]]
//
// Without paths it reads /usr/share/zoneinfo/zone.tab and tzdata.zi beside it (macOS and most Linux
// systems). zone.tab has the zones' places; tzdata.zi has the old names that are now links (such as
// Asia/Calcutta for Asia/Kolkata), which browsers still report and ICU still lists: such a name
// takes the place of the zone it links to, unless zone.tab has its own. The table is source:
// commit the result.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const DEFAULT_SOURCE = "/usr/share/zoneinfo/zone.tab";
const TARGET = join(import.meta.dirname, "../src/client/zone-centres.ts");

/**
 * ISO 6709 as zone.tab writes it, "+DDMM+DDDMM" or "+DDMMSS+DDDMMSS" (the sign leads each part),
 * into decimal degrees rounded to 2 decimals (about 1 km: far finer than a map opening at zoom 6).
 */
export function parseIso6709(text: string): readonly [number, number] {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(text);
  if (match === null) throw new Error(`Not an ISO 6709 coordinate: "${text}"`);
  const [, latSign, latDeg, latMin, latSec, lngSign, lngDeg, lngMin, lngSec] = match;
  const degrees = (sign: string, deg: string, min: string, sec: string | undefined): number => {
    const value = Number(deg) + Number(min) / 60 + Number(sec ?? "0") / 3600;
    return Math.round((sign === "-" ? -value : value) * 100) / 100 + 0;
  };
  const lat = degrees(latSign ?? "+", latDeg ?? "0", latMin ?? "0", latSec);
  const lng = degrees(lngSign ?? "+", lngDeg ?? "0", lngMin ?? "0", lngSec);
  if (Math.abs(lat) > 90 || Math.abs(lng) > 180) throw new Error(`Out of range: "${text}"`);
  return [lat, lng];
}

/** zone name -> [lat, lng] from the text of a zone.tab: columns are country, coordinates, zone. */
export function parseZoneTab(text: string): Map<string, readonly [number, number]> {
  const zones = new Map<string, readonly [number, number]>();
  for (const line of text.split("\n")) {
    if (line.trim() === "" || line.startsWith("#")) continue;
    const [, coordinates, zone] = line.split("\t");
    if (coordinates === undefined || zone === undefined) throw new Error(`Bad line: "${line}"`);
    zones.set(zone, parseIso6709(coordinates));
  }
  return zones;
}

/** "L <target> <link name>" lines of a tzdata.zi: link name -> target zone. */
export function parseLinks(text: string): Map<string, string> {
  const links = new Map<string, string>();
  for (const line of text.split("\n")) {
    const [kind, target, name] = line.split(" ");
    if (kind === "L" && target !== undefined && name !== undefined) links.set(name, target);
  }
  return links;
}

/** The zones plus every link name whose target (followed through other links) has a place. */
export function withLinks(
  zones: Map<string, readonly [number, number]>,
  links: Map<string, string>,
): Map<string, readonly [number, number]> {
  const all = new Map(zones);
  for (const name of links.keys()) {
    if (all.has(name)) continue;
    let target = links.get(name);
    for (let hops = 0; target !== undefined && !zones.has(target) && hops < 5; hops++) {
      target = links.get(target);
    }
    const centre = target === undefined ? undefined : zones.get(target);
    if (centre !== undefined) all.set(name, centre);
  }
  return all;
}

/** The text of src/client/zone-centres.ts, sorted by zone name. */
export function renderTable(zones: Map<string, readonly [number, number]>): string {
  const rows = [...zones]
    .toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([zone, [lat, lng]]) => `  ${JSON.stringify(zone)}: [${lat}, ${lng}],`);
  return [
    "// Generated by scripts/zone-centres.ts from the tz database's zone.tab (the tz database is in the",
    "// public domain). Do not edit by hand: run `npm run zones` instead.",
    "//",
    "// The main place of each IANA time zone as [latitude, longitude] in degrees, rounded to 2",
    "// decimals, for the form map's opening view (decision D63).",
    "export const ZONE_CENTRES: Readonly<Record<string, readonly [number, number]>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] === import.meta.filename) {
  const source = process.argv[2] ?? DEFAULT_SOURCE;
  const linkSource = process.argv[3] ?? join(dirname(source), "tzdata.zi");
  const zones = withLinks(
    parseZoneTab(readFileSync(source, "utf8")),
    parseLinks(readFileSync(linkSource, "utf8")),
  );
  writeFileSync(TARGET, renderTable(zones));
  process.stdout.write(`${zones.size} zones from ${source} and ${linkSource} into ${TARGET}\n`);
}
